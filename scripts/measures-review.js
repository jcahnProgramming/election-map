// Builds docs/measures-review.md: the human review checklist for ballot-measure information
// (config/elections/<election>/measures/<ST>.json, see docs/measures-data.md).
//
// Values behind the review gate (proponent_website, opposition_website, party_positions[]) are served only once their
// `reviewed` flag is true. Everything else comes from official sources and is served immediately, but is listed too so
// it can be spot-checked.
//
// Usage: node scripts/measures-review.js [electionKey]   (default: config/elections.json `current`)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ek = process.argv[2] || JSON.parse(readFileSync(path.join(root, 'config', 'elections.json'), 'utf8')).current;
const dir = path.join(root, 'config', 'elections', ek, 'measures');
if (!existsSync(dir)) {
  console.error(`No measure files for ${ek} (${dir})`);
  process.exit(1);
}

const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (s, n = 140) => { const t = cell(s); return t.length > n ? `${t.slice(0, n - 1)}…` : t; };
const link = (u) => (u ? `<${u}>` : '—');
const box = (reviewed) => (reviewed ? '[x]' : '[ ]');

const files = readdirSync(dir).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort();
let gated = 0, gatedDone = 0, measures = 0;
const body = [];
const noneStates = [];
for (const f of files) {
  const doc = JSON.parse(readFileSync(path.join(dir, f), 'utf8'));
  const st = doc.state ?? f.slice(0, 2);
  if (!doc.measures?.length) { noneStates.push(`${st}${doc.note || doc._note ? ` (${short(doc.note || doc._note, 200)})` : ''}`); continue; }
  body.push(`## ${st}\n`);
  for (const m of doc.measures) {
    measures++;
    body.push(`### ${st} · ${cell(m.measure_id)}\n`);
    body.push(`File: \`config/elections/${ek}/measures/${f}\` · official page: ${link(m.official_source_url)}\n`);
    body.push('**Needs review before it is shown** (set `"reviewed": true` in the file once checked):\n');
    body.push('| ✓ | Field | Value | Source to check |');
    body.push('|---|---|---|---|');
    const rows = [];
    if (m.proponent_website?.value) rows.push(['proponent_website', m.proponent_website.value, m.proponent_website.source_url, m.proponent_website.reviewed]);
    if (m.opposition_website?.value) rows.push(['opposition_website', m.opposition_website.value, m.opposition_website.source_url, m.opposition_website.reviewed]);
    for (const p of m.party_positions ?? []) rows.push([`party_positions: ${p.party}`, p.position, p.source_url, p.reviewed]);
    for (const [field, value, src, rev] of rows) {
      gated++; if (rev === true) gatedDone++;
      body.push(`| ${box(rev === true)} | ${cell(field)} | ${short(value)} | ${link(src)} |`);
    }
    if (!rows.length) body.push('| — | (nothing gated for this measure) | | |');
    body.push('\n**Shown immediately (official sources) — spot-check:**\n');
    body.push('| Field | Value | Source |');
    body.push('|---|---|---|');
    const sv = (field, x) => body.push(`| ${field} | ${x?.value != null ? short(x.value) : '**null**'} | ${link(x?.source_url)} |`);
    sv('official_title', m.official_title);
    sv('official_summary', m.official_summary);
    body.push(`| full_text | ${m.full_text?.value ? short(m.full_text.value, 100) : m.full_text?.url ? `link only: ${link(m.full_text.url)}` : '**null**'} | ${link(m.full_text?.source_url)} |`);
    const pb = m.placed_by;
    body.push(`| placed_by | ${pb ? cell([pb.type, pb.proponent_name, pb.bill_number].filter(Boolean).join(' · ')) : '**null**'} | ${link(pb?.source_url)} |`);
    if (m.opposition_committee_name?.value) sv('opposition_committee_name', m.opposition_committee_name);
    const lv = m.legislative_vote;
    if (lv?.chambers?.length) {
      body.push(`| legislative_vote | ${cell(lv.chambers.map((c) => `${c.chamber} ${c.yes}–${c.no}${c.by_party ? ' (by party)' : ''}`).join('; '))} | ${link(lv.roll_call_url || lv.source_url)} |`);
    }
    if (m.unsourced?.length) {
      body.push('\nNot officially sourced (left null on purpose):\n');
      for (const u of m.unsourced) body.push(`- ${cell(u)}`);
    }
    body.push('');
  }
}

const out = [
  `# Ballot measure review checklist — ${ek}`,
  '',
  '_Generated by `node scripts/measures-review.js` from `config/elections/' + ek + '/measures/*.json`. Regenerate after editing those files; don\'t edit this file by hand._',
  '',
  '## How to review',
  '',
  '1. For each unchecked row under **Needs review**, open the source link and confirm the value is exactly what that',
  '   official filing / party page says (a campaign website must be the one named in the filing or official guide; a party',
  '   position must be the party\'s own published position on *this* measure).',
  '2. If it checks out, set `"reviewed": true` on that entry in the state\'s JSON file. If it\'s wrong, fix it or delete the',
  '   entry (a missing value is fine; an unsourced one is not).',
  '3. Spot-check the **Shown immediately** rows the same way: they are already public.',
  '4. Run `node scripts/measures-review.js` to refresh this file, commit, push. No restart logic needed: the server reads',
  '   the files at startup, and every deploy restarts it.',
  '',
  `**Status:** ${measures} measures · ${gatedDone} of ${gated} gated values reviewed.`,
  '',
  noneStates.length ? `**No statewide measures on the ballot:** ${noneStates.join('; ')}\n` : '',
  ...body,
].join('\n');
writeFileSync(path.join(root, 'docs', 'measures-review.md'), out);
console.log(`docs/measures-review.md: ${measures} measures, ${gatedDone}/${gated} gated values reviewed`);
