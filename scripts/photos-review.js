// Builds docs/photos-review.md: the human review checklist for candidate photos
// (config/elections/<election>/candidates/<ST>.json, see docs/photos-data.md).
//
// A photo is served only once its entry has `"reviewed": true`, and in a contest only when every major candidate has a
// reviewed photo (otherwise everyone in that contest gets initials). This list shows, per contest, what each face is
// supposed to be, where it comes from and under which license, so a reviewer can confirm each one matches the right person.
//
// Usage: node scripts/photos-review.js [electionKey]   (default: config/elections.json `current`)
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ek = process.argv[2] || JSON.parse(readFileSync(path.join(root, 'config', 'elections.json'), 'utf8')).current;
const dir = path.join(root, 'config', 'elections', ek, 'candidates');
if (!existsSync(dir)) {
  console.error(`No candidate photo files for ${ek} (${dir})`);
  process.exit(1);
}

const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const link = (u, label) => (u ? `[${label ?? 'link'}](${u})` : '—');
const OFFICE = { senate: 'U.S. Senate', governor: 'Governor', house: 'U.S. House' };
const order = (e) => `${['senate', 'governor', 'house'].indexOf(e.office)}-${String(e.district ?? '').padStart(3, '0')}`;

const files = readdirSync(dir).filter((f) => /^[A-Z]{2}\.json$/.test(f)).sort();
let total = 0, withPhoto = 0, reviewed = 0, contestsAll = 0, contestsReady = 0;
const byType = {};
const body = [];
for (const f of files) {
  const doc = JSON.parse(readFileSync(path.join(dir, f), 'utf8'));
  const st = doc.state ?? f.slice(0, 2);
  const contests = new Map();
  for (const e of doc.candidates ?? []) {
    const k = `${e.office}|${e.district ?? ''}`;
    if (!contests.has(k)) contests.set(k, []);
    contests.get(k).push(e);
  }
  body.push(`## ${st}\n`);
  body.push(`File: \`config/elections/${ek}/candidates/${f}\`\n`);
  for (const list of [...contests.values()].sort((a, b) => order(a[0]).localeCompare(order(b[0])))) {
    const e0 = list[0];
    contestsAll++;
    const missing = list.filter((e) => !e.photo_url && e.party !== 'OTHER').map((e) => e.match[0]);
    const ready = !missing.length && list.some((e) => e.photo_url);
    if (ready) contestsReady++;
    body.push(`### ${st} · ${OFFICE[e0.office] ?? e0.office}${e0.district ? ` District ${e0.district}` : ''}\n`);
    body.push(ready
      ? '_Every DEM / REP candidate listed has a photo: once all major candidates are reviewed, photos show for this contest (other-party nominees need one too)._\n'
      : `_Initials for everyone in this contest until these have a reviewed photo: ${missing.length ? missing.map(cell).join(', ') : 'no photos found yet'}._\n`);
    body.push('| ✓ | Candidate | Party | Photo | Source page | Type | License | Credit | Note |');
    body.push('|---|---|---|---|---|---|---|---|---|');
    for (const e of list) {
      total++;
      if (e.photo_url) { withPhoto++; byType[e.source_type] = (byType[e.source_type] ?? 0) + 1; }
      if (e.photo_url && e.reviewed === true) reviewed++;
      body.push(`| ${e.photo_url ? (e.reviewed === true ? '[x]' : '[ ]') : '—'} | ${cell(e.match.join(' / '))} | ${cell(e.party)} | ${e.photo_url ? link(e.photo_url, 'photo') : 'none'} | ${link(e.source_page_url, 'source')} | ${cell(e.source_type)} | ${cell(e.license)} | ${cell(e.credit)} | ${cell(e.note ?? '')} |`);
    }
    body.push('');
  }
}

const out = [
  `# Candidate photo review checklist — ${ek}`,
  '',
  `_Generated by \`node scripts/photos-review.js\` from \`config/elections/${ek}/candidates/*.json\`. Regenerate after editing those files; don't edit this file by hand._`,
  '',
  '## How to review',
  '',
  '1. For each row with a photo, open **photo** and **source**: confirm the face is this candidate (same office / state /',
  '   district; same-name people exist), that the source is allowed (official portrait, Wikimedia Commons with the license',
  '   shown on its File: page, or a campaign press page that offers the headshot for media use), and that license and credit',
  '   match the source page exactly.',
  '2. If it checks out, set `"reviewed": true` on that entry. If not, set `photo_url` (and the source fields) to null and',
  '   say why in `note`. A missing photo is fine; a wrong or unlicensed one is not.',
  '3. Fairness: a contest shows photos only when every major candidate (party nominees, and anyone at 5% or more of the',
  '   votes counted) has a reviewed photo. Otherwise everyone in it gets initials, so reviewing one side alone changes nothing.',
  '4. Run `node scripts/photos-review.js`, commit, push. The server fetches each newly reviewed photo once on startup,',
  '   resizes it and serves it from our own domain.',
  '',
  `**Status:** ${total} candidates · ${withPhoto} with a photo source (${Object.entries(byType).map(([k, v]) => `${k}: ${v}`).join(', ') || 'none'}) · ${reviewed} reviewed · ${contestsReady} of ${contestsAll} contests have a photo for every DEM / REP candidate listed.`,
  '',
  ...body,
].join('\n');
writeFileSync(path.join(root, 'docs', 'photos-review.md'), out);
console.log(`docs/photos-review.md: ${total} candidates, ${withPhoto} with photos, ${reviewed} reviewed, ${contestsReady}/${contestsAll} contests photo-ready`);
